import assert from 'node:assert/strict';
import '../assets/enhancement-ledger.js';
const E=globalThis.MapleEnhancements;
const raw={id:'october-soul',character_name:'검증용',target_item:'제네시스 스태프',date_create:'2026-09-24T12:00:00+09:00',soul_potential_amplified_grade:3,before_soul_potential_option:[{grade:'유니크',value:'이전 옵션'}],after_soul_potential_option:[{grade:'레전드리',value:'다음 옵션'}]};
const legacy=E.event('soul-potential',raw,'fixture',1);
assert.equal(legacy.miracleTimeFlag,'');
const refreshed=E.event('soul-potential',{...raw,miracle_time_flag:'1'},'fixture',2);
assert.equal(refreshed.miracleTimeFlag,'1');
assert.equal(E.flag(refreshed.miracleTimeFlag),true);
assert.equal(E.groups({events:[legacy]})[0].key,E.groups({events:[refreshed]})[0].key,'API 메타데이터 보강으로 저장한 단가 키가 바뀌면 안 됨');
assert.equal(E.defaultUnit(legacy),E.defaultUnit(refreshed),'미라클 표시는 실제 재설정 단가를 변경하지 않음');
const state=E.merge({events:[legacy]});
const confirmed=E.confirm(state,E.groups(state)[0],'195000000','fixture-batch');
const repaired=E.merge(confirmed,{events:[refreshed]});
assert.equal(repaired.events.length,1);
assert.equal(repaired.events[0].miracleTimeFlag,'1');
assert.deepEqual(E.profits(repaired),E.profits(confirmed),'과거 확정 지출과 중복 방지 유지');
assert.equal(E.groups(repaired).length,0);
assert.equal(E.event('soul-potential',{...raw,miracle_time_flag:'0'},'fixture').miracleTimeFlag,'0');
console.log('10월 소울 미라클 메타데이터·과거 확정 지출 보존 검증 통과');

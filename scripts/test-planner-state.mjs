import assert from 'node:assert/strict';
await import('../assets/planner-state.js');
const S=globalThis.MaplePlannerState;
assert.equal(S.dateKst(Date.parse('2026-10-28T15:00:00Z')),'2026-10-29');
assert.equal(S.weekKst('2026-10-28'),'2026-10-22');
assert.equal(S.weekKst('2026-11-01'),'2026-10-29');
const large='9999999999999999999999999';
const original={investments:[{id:'p',amount:large,updatedAt:1}],future:{keep:true}};
const copy=JSON.stringify(original),removed=S.merge(original,{investments:[{id:'p',amount:large,updatedAt:3,deletedAt:3}]});
assert.equal(JSON.stringify(original),copy);assert.equal(removed.investments[0].amount,large);
assert.equal(S.active(removed.investments).length,0);
assert.equal(S.active(S.merge(removed,original).investments).length,0,'오래된 원격본이 삭제한 계획을 되살리지 않음');
assert.deepEqual(S.merge({funds:[{id:'a',updatedAt:1}]},{funds:[{id:'b',updatedAt:2}]}).funds.map(x=>x.id),['a','b']);
assert.deepEqual(S.normalize(original).future,{keep:true});
const a={huntNotes:[{id:'same',minutes:10,updatedAt:100}]},b={huntNotes:[{id:'same',minutes:20,updatedAt:100}]};
assert.deepEqual(S.merge(a,b),S.merge(b,a),'동시간 충돌도 병합 순서와 무관하게 수렴');
const saleA={id:'sale-A',quantity:1,unitPrice:large,updatedAt:2},saleB={id:'sale-B',quantity:1,unitPrice:'200',updatedAt:3};
const deviceA={trades:[{id:'trade',quantity:2,updatedAt:2,sales:[saleA]}]},deviceB={trades:[{id:'trade',quantity:2,updatedAt:3,sales:[saleB]}]};
const joined=S.merge(deviceA,deviceB);
assert.deepEqual(joined.trades[0].sales.map(row=>row.id),['sale-A','sale-B'],'같은 아이템에 두 기기가 각각 추가한 판매를 모두 보존');
assert.equal(joined.trades[0].sales[0].unitPrice,large);
assert.deepEqual(joined,S.merge(deviceB,deviceA),'판매 병합 순서와 무관하게 수렴');
const canceled={trades:[{id:'trade',quantity:2,updatedAt:4,sales:[{...saleA,updatedAt:4,deletedAt:4},saleB]}]};
assert.equal(S.active(S.merge(canceled,deviceA,deviceB).trades[0].sales).length,1,'오래된 기기의 판매 기록이 취소한 판매를 되살리지 않음');
const conflict={trades:[{id:'trade',quantity:1,updatedAt:3,sales:[saleB]}]};
assert.equal(S.merge(deviceA,conflict).trades[0].sales.length,2,'획득 수량 초과 충돌도 임의 삭제 없이 보존');
const simultaneous={trades:[{id:'trade',quantity:2,note:'B',updatedAt:2,sales:[saleB]}]};
assert.deepEqual(S.merge(deviceA,simultaneous,canceled),S.merge(deviceA,S.merge(simultaneous,canceled)),'중첩 판매 병합도 여러 기기에서 수렴');
assert.deepEqual(S.merge(joined,joined),joined,'같은 판매를 재병합해도 중복되지 않음');
const expired=S.normalize({investments:[{id:'p',name:'투자 기록',amount:large,equipment:{fetchedAt:Date.now()-31*86400000,itemName:'오래된 API 캐시'}}]});
assert.equal(expired.investments[0].name,'투자 기록');assert.equal(expired.investments[0].amount,large);assert(!expired.investments[0].equipment);
console.log('계획 저장: KST 경계·정밀 금액·병합/삭제표식·원본불변·API 캐시분리 통과');

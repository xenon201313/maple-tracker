import assert from 'node:assert/strict';
import { authFailureDiagnostic, safeAuthDiagnostic } from '../cloudflare-worker/friends-auth-diagnostic.mjs';

const privateValue = 'private-response-token-and-reference';
const response = (body, headers={}) => new Response(body, {status:403,headers:{'Content-Type':'text/html',...headers}});
for (const item of [
  {body:'<html>'+privateValue+'</html>',headers:{server:privateValue,'cf-mitigated':privateValue},expected:{mitigation:'UNCLASSIFIED',gateway:'OTHER',page:'UNCLASSIFIED'}},
  {body:'<html>'+privateValue+'</html>',headers:{server:'cloudflare'},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFLARE',page:'UNCLASSIFIED'}},
  {body:privateValue,headers:{server:'cloudflare','cf-error-type':'1020'},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFLARE',page:'CLOUDFLARE_ERROR_1020'}},
  {body:privateValue,headers:{server:'cloudflare','cf-error-type':privateValue},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFLARE',page:'UNCLASSIFIED'}},
  {body:'<h1>Error <span>1042</span></h1>'+privateValue,headers:{server:'cloudflare'},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFLARE',page:'CLOUDFLARE_ERROR_1042'}},
  {body:'<h1>Sorry, you have been blocked</h1>'+privateValue+' Cloudflare',headers:{server:'cloudflare'},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFLARE',page:'CLOUDFLARE_BLOCKED'}},
  {body:'<title>Just a moment...</title>'+privateValue+' Cloudflare',headers:{server:'cloudflare'},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFLARE',page:'CLOUDFLARE_CHALLENGE_PAGE'}},
  {body:'<h1>Error 1999</h1>'+privateValue,headers:{server:'cloudflare'},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFLARE',page:'UNCLASSIFIED'}},
  {body:'<title>Access Denied</title><a href="https://errors.edgesuite.net/private">'+privateValue+'</a>',headers:{server:'AkamaiGHost'},expected:{mitigation:'UNCLASSIFIED',gateway:'AKAMAI',page:'AKAMAI_ACCESS_DENIED'}},
  {body:'The request could not be satisfied. Generated by cloudfront. '+privateValue,headers:{'x-amz-cf-id':privateValue},expected:{mitigation:'UNCLASSIFIED',gateway:'CLOUDFRONT',page:'CLOUDFRONT_ERROR'}}
]) {
  const result=await authFailureDiagnostic(response(item.body,item.headers));
  assert.deepEqual(result,item.expected);
  assert(!JSON.stringify(result).includes(privateValue));
  assert.deepEqual(safeAuthDiagnostic({...result,rawBody:privateValue}),result);
}
assert.equal(safeAuthDiagnostic({mitigation:privateValue,gateway:'OTHER',page:'UNCLASSIFIED'}),null);
assert.equal(safeAuthDiagnostic({mitigation:'UNCLASSIFIED',gateway:privateValue,page:'UNCLASSIFIED'}),null);
assert.equal(safeAuthDiagnostic({mitigation:'UNCLASSIFIED',gateway:'OTHER',page:privateValue}),null);

let reads=0,cancelled=false;
const stream=new ReadableStream({
  pull(controller) {reads++;controller.enqueue(new TextEncoder().encode('x'.repeat(4096)));},
  cancel() {cancelled=true;}
});
assert.deepEqual(await authFailureDiagnostic(response(stream)),{mitigation:'UNCLASSIFIED',gateway:'ABSENT',page:'UNCLASSIFIED'});
assert(cancelled,'8KB까지만 읽고 나머지 응답을 취소해야 한다.');
assert(reads<=3,'무한 응답을 계속 읽으면 안 된다.');
console.log('인증 거부 진단: 고정 분류·원문 비노출·8KB 제한·본문 취소 통과. 실제 네트워크 요청 없음.');
